-- 1. TABELA DE MECÂNICAS / OFICINAS CADASTRADAS NA CIDADE
CREATE TABLE IF NOT EXISTS mecanicas (
  id TEXT PRIMARY KEY,
  nome TEXT NOT NULL,
  cor TEXT DEFAULT '#ec4899',
  icone TEXT DEFAULT '🛠️',
  ativo BOOLEAN DEFAULT TRUE,
  criado_em TIMESTAMPTZ DEFAULT NOW()
);

